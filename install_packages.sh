#!/bin/bash

# --- Script Configuration ---
# Set strict mode to catch errors early
set -o errexit
set -o nounset
set -o pipefail

# --- Script Variables ---
SCRIPT_NAME=$(basename "$0")
AIR_GAPPED_MODE=0
SAVE_MODE=0
ONLINE_MODE=0
base_dir=$(pwd)
PACKAGES_LIST=()
mode_msg=""
os_id=""
rpm_pm=""
source_dir=""
# Tracks which package manager currently has the temporary local offline repo
# configured, so the EXIT trap can always restore the original configuration.
OFFLINE_REPO_ACTIVE=""
# Set to 1 while an offline-packages staging directory created by THIS run
# exists, so the EXIT trap only ever removes what this run created.
STAGING_CREATED=0


usage() {
    cat << EOF
Usage: $SCRIPT_NAME [offline] [save] [online] [package1 package2 package3 ...]

This script must be run with root privileges.
At least one parameter is required followed by a list of packages to install. [save] and [online] may be used together followed by the package(s) list. [offline] must be used alone followed by the package(s) list.

Parameters:
  offline         : Installs packages from an offline tarball that was generated by this script.
                    Tarball must be placed in the same directory as this script. Offline host must be running the same OS type and version.
  save            : Downloads and saves packages and dependencies as an offline install tarball.
  online          : Install packages and dependencies from the internet using default package manager repositories.
  [package(s)...] : A space separated list of package names to process.

Options:
  -h, --help      : Show this help and exit.

Example:
  Only install the packages:
  sudo ./$SCRIPT_NAME online python3 python3-pip

  Only save the packages:
  sudo ./$SCRIPT_NAME save python3 python3-pip

  Save and install the packages:
  sudo ./$SCRIPT_NAME save online python3 python3-pip

  Install packages from an offline tarball:
  sudo ./$SCRIPT_NAME offline python3 python3-pip
EOF
    exit "${1:-1}"
}

os_type() {
    # Get OS information from /etc/os-release
    if [[ -f /etc/os-release ]]; then
        # shellcheck disable=SC1091
        source /etc/os-release
        os_id="$ID"
    else
        echo "Error: Unknown or unsupported OS $os_id."
        exit 1
    fi
}

detect_rpm_pm() {
  # Pick the rpm-family package manager once, so install branches cannot drift
  if command -v dnf &> /dev/null; then
    rpm_pm="dnf"
  elif command -v yum &> /dev/null; then
    rpm_pm="yum"
  else
    echo "Error: Neither dnf nor yum found on this system." >&2
    exit 1
  fi
}

cleanup_on_exit() {
  # Runs on EVERY exit (success, failure, interrupt). Restores the package
  # manager configuration and removes only what this run created.
  local rc=$?
  restore_local_repo
  if [[ $STAGING_CREATED -eq 1 ]]; then
    rm -rf "$base_dir/offline-packages"
  fi
  rm -f "$base_dir/offline-packages.tar.gz.tmp"
  exit "$rc"
}

setup_local_repo() {
  # Point the host's package manager at the extracted offline-packages
  # directory. Every path here is guarded so a re-run after an interrupted
  # run cannot cascade backups or leak the trusted local repo.
  case "$os_id" in
    ubuntu|debian)
      source_dir="/etc/apt/sources.list.d"
      OFFLINE_REPO_ACTIVE="apt"
      if [ -d "$source_dir" ]; then
          # Remove any stale copy of our own repo file so it is never backed
          # up or restored as if it were a real source
          rm -f "$source_dir/offline-packages.list" "$source_dir/offline-packages.list.bak"
          for file in "$source_dir"/*; do
              [ -e "$file" ] || continue
              case "$file" in
                  *.bak) continue ;; # leftover backup from an interrupted run; restored after install
              esac
              mv "$file" "${file}.bak"
          done
          [ -e "/etc/apt/sources.list" ] && mv -n /etc/apt/sources.list /etc/apt/sources.list.bak
      else
          echo "  Sources.list directory not found. Skipping backup."
      fi
      echo "deb [trusted=yes] file:$local_repo_dir ./" | tee /etc/apt/sources.list.d/offline-packages.list &> /dev/null
      ;;
    rhel|centos|rocky|almalinux|fedora)
      OFFLINE_REPO_ACTIVE="rpm"
      echo "  Creating local repository..."
      cat <<EOF | tee /etc/yum.repos.d/offline-packages.repo
[offline-packages-repo]
name=Offline Packages Repository
baseurl=file://$local_repo_dir
enabled=1
gpgcheck=0
EOF
      ;;
    sles|opensuse-leap)
      OFFLINE_REPO_ACTIVE="zypper"
      echo "  Adding temporary local repository..."
      if zypper lr offline-packages-repo &> /dev/null; then
          # stale repo left behind by an interrupted run
          zypper --non-interactive removerepo offline-packages-repo
      fi
      zypper --non-interactive addrepo -G "file://$local_repo_dir" "offline-packages-repo"
      zypper --non-interactive refresh offline-packages-repo
      ;;
  esac
}

restore_local_repo() {
  # Restore the original package manager configuration. Idempotent: safe to
  # call twice (success path and the EXIT trap).
  case "$OFFLINE_REPO_ACTIVE" in
    apt)
      rm -f /etc/apt/sources.list.d/offline-packages.list
      if [ -d "$source_dir" ]; then
          for file in "$source_dir"/*.bak; do
              [ -e "$file" ] || continue
              mv -f "$file" "${file%.bak}"
          done
      fi
      [ -e "/etc/apt/sources.list.bak" ] && mv -f /etc/apt/sources.list.bak /etc/apt/sources.list
      ;;
    rpm)
      rm -f /etc/yum.repos.d/offline-packages.repo
      ;;
    zypper)
      if zypper lr offline-packages-repo &> /dev/null; then
          zypper --non-interactive removerepo offline-packages-repo || true
      fi
      ;;
  esac
  OFFLINE_REPO_ACTIVE=""
}

with_local_repo() {
  # Set up the temporary local offline repo, run the given install command,
  # and always restore the original repo configuration (the EXIT trap covers
  # every failure path in between).
  setup_local_repo
  "$@"
  echo "  Restoring repositories..."
  restore_local_repo
}

apt_install_packages() {
  # Shared by the online and offline apt paths (offline points apt at the
  # local repo via setup_local_repo first)
  if ! apt-get update -qq; then
      echo "Error: apt-get update failed." >&2
      return 1
  fi
  if ! echo "" | DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${PACKAGES_LIST[@]}"; then
      echo "Error: apt-get install failed." >&2
      return 1
  fi
}

rpm_offline_install() {
  $rpm_pm clean all
  if ! $rpm_pm --disablerepo="*" --enablerepo="offline-packages-repo" install -y "${PACKAGES_LIST[@]}"; then
      echo "Error: $rpm_pm install failed." >&2
      return 1
  fi
}

zypper_offline_install() {
  # Scoped to the local repo only - the host's configured repos are left
  # untouched and are never used for resolution
  if ! zypper --non-interactive --no-refresh install -y --repo offline-packages-repo "${PACKAGES_LIST[@]}"; then
      echo "Error: zypper install failed." >&2
      return 1
  fi
}

validate_archive_contents() {
  # Fail early if the extracted archive does not contain packages for this
  # host's OS family (e.g. a .deb archive on a Rocky/Leap host)
  local pkg_ext=""
  case "$os_id" in
    ubuntu|debian) pkg_ext="deb" ;;
    rhel|centos|rocky|almalinux|fedora|sles|opensuse-leap) pkg_ext="rpm" ;;
  esac
  if [[ -n "$pkg_ext" ]] && [[ -z "$(find "$base_dir/offline-packages" -name "*.${pkg_ext}" 2> /dev/null)" ]]; then
      echo "Error: offline-packages.tar.gz contains no .${pkg_ext} packages for this OS ($os_id)." >&2
      echo "       The archive was likely created on a different OS family. Re-create it with 'save' on a matching host." >&2
      exit 1
  fi
}

validate_runtime() {

  # Determine mode and packages
  if [[ $AIR_GAPPED_MODE -eq 1 ]]; then
    if [[ $SAVE_MODE -eq 1 ]]; then
      echo "Error: 'offline' and 'save' modes cannot be used together."
      usage
    fi
    if [[ $ONLINE_MODE -eq 1 ]]; then
      echo "Error: 'offline' and 'online' modes cannot be used together."
      usage
    fi
    if [[ -f "$base_dir/offline-packages.tar.gz" ]]; then
      if [[ -d "$base_dir/offline-packages" ]]; then
        echo "  Removing stale offline-packages staging directory..."
        rm -rf "$base_dir/offline-packages"
      fi
      echo "  Extracting tarball..."
      STAGING_CREATED=1
      tar -xzf "$base_dir/offline-packages.tar.gz" -C "$base_dir"
      validate_archive_contents
    else
      echo "Error: Tarball not found. Place it in the same directory as this script."
      exit 1
    fi
  fi
  if [[ $AIR_GAPPED_MODE -eq 0 ]]; then
    if [[ $ONLINE_MODE -eq 0 ]] && [[ $SAVE_MODE -eq 0 ]]; then
      echo "Error: One of 'offline', 'save', or 'online' modes must be specified."
      usage
    fi
  fi
  if [[ ${#PACKAGES_LIST[@]} -eq 0 ]]; then
      echo "Error: No packages specified."
      usage
  fi
}

install_packages() {
  local_repo_dir="$base_dir/offline-packages"
  case "$os_id" in
    ubuntu|debian)
      if [[ $AIR_GAPPED_MODE -eq 1 ]]; then
        with_local_repo apt_install_packages
      elif [[ $ONLINE_MODE -eq 1 ]]; then
        apt_install_packages
      else
        echo "Error: Installation method not specified."
        exit 1
      fi
      ;;
    rhel|centos|rocky|almalinux|fedora)
      detect_rpm_pm
      if [[ $AIR_GAPPED_MODE -eq 1 ]]; then
        with_local_repo rpm_offline_install
        echo "  Package install finished"
      elif [[ $ONLINE_MODE -eq 1 ]]; then
        $rpm_pm clean all
        if ! $rpm_pm install -y "${PACKAGES_LIST[@]}"; then
            echo "Error: $rpm_pm install failed." >&2
            return 1
        fi
        echo "  Package install finished"
      else
        echo "Error: Installation method not specified."
        exit 1
      fi
      ;;
    sles|opensuse-leap)
      if [[ $AIR_GAPPED_MODE -eq 1 ]]; then
        with_local_repo zypper_offline_install
        echo "  Package install finished"
      elif [[ $ONLINE_MODE -eq 1 ]]; then
        zypper --non-interactive refresh
        if ! zypper --non-interactive install -y "${PACKAGES_LIST[@]}"; then
            echo "Error: zypper install failed." >&2
            return 1
        fi
        echo "  Package install finished"
      else
        echo "Error: Installation method not specified."
        exit 1
      fi
      ;;
    *)
      echo "Error: Unsupported OS '$os_id'. Manual install of packages required."
      exit 1
      ;;
  esac

}

save_packages() {
  DOWNLOAD_DIR="$base_dir/offline-packages"
  if [[ -d "$DOWNLOAD_DIR" ]]; then
    echo "  Removing stale offline-packages staging directory..."
    rm -rf "$DOWNLOAD_DIR"
  fi
  mkdir -p "$DOWNLOAD_DIR"
  STAGING_CREATED=1
  case "$os_id" in
    ubuntu|debian)
      echo "  installing dpkg-dev"
      apt-get update -qq
      echo "" | DEBIAN_FRONTEND=noninteractive apt-get install -y -qq dpkg-dev
      cd "$DOWNLOAD_DIR"
      local packages_to_download
      packages_to_download=$(apt-cache depends --recurse --no-recommends --no-suggests --no-conflicts --no-breaks --no-replaces --no-enhances --no-pre-depends "${PACKAGES_LIST[@]}" | grep "^\w" || true)
      if [[ -z "$packages_to_download" ]]; then
          echo "Error: Failed to resolve dependencies for packages. Aborting." >&2
          cd "$base_dir"
          return 1
      fi
      # shellcheck disable=SC2086
      if ! apt-get download -qq $packages_to_download; then
          echo "Error: apt-get download failed." >&2
          cd "$base_dir"
          return 1
      fi
      dpkg-scanpackages -m . > Packages
      cd "$base_dir"
      ;;
    rhel|centos|rocky|almalinux|fedora)
      dnf install -y dnf-utils createrepo_c
      # --alldeps: download the FULL dependency closure, including packages
      # already installed on this host, so the archive works on minimal images
      dnf download --resolve --alldeps --downloaddir="$DOWNLOAD_DIR" "${PACKAGES_LIST[@]}"
      createrepo_c "$DOWNLOAD_DIR"
      ;;
    sles|opensuse-leap)
      zypper --non-interactive refresh
      zypper --non-interactive install -y createrepo_c
      # Use a private package cache dir so the host's zypper cache is never
      # touched, and download the named packages with 'zypper download' so
      # they are fetched even when already installed on this host
      zypp_cache="$DOWNLOAD_DIR/.zypp-cache"
      mkdir -p "$zypp_cache"
      zypper --non-interactive --pkg-cache-dir "$zypp_cache" download "${PACKAGES_LIST[@]}"
      # Also download any dependencies not yet installed on this host
      zypper --non-interactive --pkg-cache-dir "$zypp_cache" install -y --download-only --auto-agree-with-licenses "${PACKAGES_LIST[@]}"
      find "$zypp_cache" -name "*.rpm" -exec cp {} "$DOWNLOAD_DIR" \;
      rm -rf "$zypp_cache"
      createrepo_c "$DOWNLOAD_DIR"
      # Known limitation: zypper has no dnf-style --alldeps, so dependencies that
      # are ALREADY INSTALLED on this build host are not fetched by either command
      # above and will be missing from the archive on a minimal target.
      echo "  NOTE: zypper cannot bundle dependencies already installed on this build host."
      echo "        For guaranteed air-gap closure, run 'save' on a minimal/fresh SUSE host."
      ;;
    *)
      echo "Error: Unsupported OS '$os_id'. Manual download of packages may be required for air-gapped mode." >&2
      return 1
      ;;
  esac
  # Verify packages actually landed in the staging directory before archiving
  if [[ -z "$(find "$DOWNLOAD_DIR" -name "*.deb" -o -name "*.rpm" 2> /dev/null)" ]]; then
      echo "Error: No package files were downloaded into $DOWNLOAD_DIR. Aborting." >&2
      return 1
  fi
  # Write the archive atomically so an interrupted save never leaves a
  # truncated offline-packages.tar.gz behind
  tar -czf "$base_dir/offline-packages.tar.gz.tmp" -C "$base_dir" "offline-packages"
  mv -f "$base_dir/offline-packages.tar.gz.tmp" "$base_dir/offline-packages.tar.gz"
  rm -rf "$DOWNLOAD_DIR"
  STAGING_CREATED=0
}

# --- Main Script --- #

# Check for root or sudo
if [[ $EUID -ne 0 ]]; then
    echo "Error: This script must be run with sudo or as root."
    usage
fi

# Always restore package manager configuration and clean up staging on exit,
# preserving the real exit code (success and failure paths alike)
trap cleanup_on_exit EXIT

# Verify Operating System
os_type

# Parse command-line arguments
while [[ $# -gt 0 ]]; do
    case "$1" in
        -h|--help)
            usage 0
            ;;
        offline)
            AIR_GAPPED_MODE=1
            shift
            ;;
        save)
            SAVE_MODE=1
            shift
            ;;
        online)
            ONLINE_MODE=1
            shift
            ;;
        -*)
            echo "Error: Unknown option '$1'."
            usage
            ;;
        *)
            PACKAGES_LIST+=("$1")
            shift
            ;;
    esac
done

# Validate Execution
validate_runtime

# Display script settings
echo "### Package Installer Started at $(date) ###"
echo "  AIR_GAPPED_MODE: $AIR_GAPPED_MODE"
echo "  SAVE_MODE: $SAVE_MODE"
echo "  ONLINE_MODE: $ONLINE_MODE"
echo "  PACKAGES_LIST: ${PACKAGES_LIST[@]}"
echo "  OS: $ID"

# Save runs BEFORE install so 'save online' archives capture the packages
# regardless of what is already installed on this host
if [[ $SAVE_MODE -eq 1 ]]; then
  echo "--- Saving [ ${PACKAGES_LIST[@]} ] on $os_id..."
  save_packages
  echo "  Copy $base_dir/offline-packages.tar.gz and $SCRIPT_NAME to air-gapped host and run:"
  echo "    sudo ./$SCRIPT_NAME offline ${PACKAGES_LIST[@]}"
fi
if [[ $AIR_GAPPED_MODE -eq 1 ]] || [[ $ONLINE_MODE -eq 1 ]]; then
  echo "--- Installing [ ${PACKAGES_LIST[@]} ] on $os_id..."
  install_packages
  echo "--- Finished installing ${PACKAGES_LIST[@]} on $os_id"
fi
echo "### Package Installer Ended at $(date) ###"

# --- End Main Script --- #